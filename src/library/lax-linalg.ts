// Linear algebra functions, mirroring `jax.lax.linalg`.

import * as laxLib from "./lax";
import { moveaxis } from "./numpy";
import * as numpy from "./numpy";
import { Array, type ArrayLike, fudgeArray } from "../frontend/array";
import * as core from "../frontend/core";
import { vmap } from "../frontend/vmap";

/**
 * Compute the Cholesky decomposition of a symmetric positive-definite matrix.
 *
 * The Cholesky decomposition of a matrix `A` is:
 *
 * - A = L @ L^T  (for upper=false, default)
 * - A = U^T @ U  (for upper=true)
 *
 * where `L` is a lower-triangular matrix and `U` is an upper-triangular matrix.
 * The input matrix must be symmetric and positive-definite.
 *
 * @example
 * ```ts
 * import { lax, numpy as np } from "@hamk-uas/jax-js-nonconsuming";
 *
 * using x = np.array([[2., 1.], [1., 2.]]);
 *
 * // Lower Cholesky factorization (default):
 * using L = lax.linalg.cholesky(x);
 * // L ≈ [[1.4142135, 0], [0.70710677, 1.2247449]]
 *
 * // Upper Cholesky factorization:
 * using U = lax.linalg.cholesky(x, { upper: true });
 * // U ≈ [[1.4142135, 0.70710677], [0, 1.2247449]]
 * ```
 */
export function cholesky(
  a: ArrayLike,
  { upper = false }: { upper?: boolean } = {},
): Array {
  const arr = fudgeArray(a);
  const n = arr.shape[arr.ndim - 1] as number;

  // Pure-primitive polyfill: only inside makeJaxpr tracing (JIT/scan body)
  // where arrays are fully abstract JaxprTracers. Produces unrolled
  // Cholesky-Banachiewicz kernel equations instead of a Routine dispatch,
  // enabling block-map fusion in scan/block-map bodies.
  if (core.inMakeJaxprBody() && n <= CHOLESKY_UNROLL_LIMIT) {
    const L = choleskyBatched(arr);
    if (upper) {
      using l = L;
      return moveaxis(l, -2, -1);
    }
    return L;
  }

  if (upper) {
    using L = core.cholesky(arr) as Array;
    return moveaxis(L, -2, -1);
  }
  return core.cholesky(arr) as Array;
}

/**
 * LU decomposition with partial pivoting.
 *
 * Computes the matrix decomposition: `P @ A = L @ U`, where `P` is a
 * permutation of the rows of `A`, `L` is lower-triangular with unit diagonal,
 * and `U` is upper-triangular.
 *
 * @param x - A batch of matrices with shape `[..., m, n]`.
 *
 * @returns A tuple `(lu, pivots, permutation)` where:
 * - `lu`: combined lower and upper triangular matrices.
 * - `pivots`: an array of pivot indices with shape `[..., min(m, n)]`.
 * - `permutation`: the permutation generated by pivots with shape `[..., m]`.
 *
 * @example
 * ```ts
 * import { lax, numpy as np } from "@hamk-uas/jax-js-nonconsuming";
 *
 * const A = np.array([[4., 3.], [6., 3.]]);
 * const [lu, pivots, permutation] = lax.linalg.lu(A);
 * // lu ≈ [[6., 3.], [0.6666667, 1.0]]
 * // pivots = [1, 1]
 * // permutation = [1, 0]
 *
 * A.dispose();
 * lu.dispose();
 * pivots.dispose();
 * permutation.dispose();
 * ```
 */
export function lu(x: ArrayLike): [Array, Array, Array] {
  return core.lu(x) as [Array, Array, Array];
}

/**
 * QR decomposition.
 *
 * Computes the thin QR factorization `A = Q @ R`, where `Q` has orthonormal
 * columns and `R` is upper triangular.
 *
 * @param a - A batch of matrices with shape `[..., m, n]` where `m >= n`.
 *
 * @returns A tuple `[Q, R]` where:
 * - `Q`: orthogonal matrix with shape `[..., m, k]`, `k = min(m, n)`.
 * - `R`: upper triangular matrix with shape `[..., k, n]`.
 *
 * @example
 * ```ts
 * import { lax, numpy as np } from "@hamk-uas/jax-js-nonconsuming";
 *
 * const A = np.array([[1., 2.], [3., 4.], [5., 6.]]);
 * const [Q, R] = lax.linalg.qr(A);
 * // Q has shape [3, 2], R has shape [2, 2]
 * // Q^T @ Q ≈ I, Q @ R ≈ A
 *
 * A.dispose();
 * Q.dispose();
 * R.dispose();
 * ```
 */
export function qr(a: ArrayLike): [Array, Array] {
  const arr = fudgeArray(a);
  return householderQRBatched(arr);
}

/**
 * Solve a triangular linear system.
 *
 * Solves `a @ x = b` (if leftSide=true) or `x @ a = b` (if leftSide=false)
 * where `a` is a triangular matrix.
 *
 * @example
 * ```ts
 * import { lax, numpy as np } from "@hamk-uas/jax-js-nonconsuming";
 *
 * using L = np.array([[2., 0.], [1., 3.]]);
 * using b = np.array([4., 7.]).reshape([2, 1]);
 *
 * // Solve L @ x = b
 * using x = lax.linalg.triangularSolve(L, b, { leftSide: true, lower: true });
 * // x = [[2.], [5./3.]]
 * ```
 */
export function triangularSolve(
  a: ArrayLike,
  b: ArrayLike,
  {
    leftSide = false,
    lower = false,
    transposeA = false,
    unitDiagonal = false,
  }: {
    leftSide?: boolean;
    lower?: boolean;
    transposeA?: boolean;
    unitDiagonal?: boolean;
  } = {},
): Array {
  a = fudgeArray(a);
  b = fudgeArray(b);
  const n = (a as Array).shape[(a as Array).ndim - 1] as number;

  // Pure-primitive polyfill: only inside makeJaxpr tracing (JIT/scan body)
  // where arrays are fully abstract JaxprTracers. Produces unrolled
  // back-substitution kernel equations instead of a Routine dispatch,
  // enabling block-map fusion in scan bodies.
  if (core.inMakeJaxprBody() && n <= TRISOLVE_UNROLL_LIMIT) {
    return triangularSolveBatched(a as Array, b as Array, {
      leftSide,
      lower,
      transposeA,
      unitDiagonal,
    });
  }

  // Routine path: delegates to backend-optimized TriangularSolve
  return triangularSolveRoutine(a as Array, b as Array, {
    leftSide,
    lower,
    transposeA,
    unitDiagonal,
  });
}

/**
 * Original triangularSolve implementation via core.triSolve (Routine dispatch).
 * @internal
 */
function triangularSolveRoutine(
  a: Array,
  b: Array,
  {
    leftSide,
    lower,
    transposeA,
    unitDiagonal,
  }: {
    leftSide: boolean;
    lower: boolean;
    transposeA: boolean;
    unitDiagonal: boolean;
  },
): Array {
  using d = new DisposableStack();
  if (!leftSide) {
    transposeA = !transposeA;
  } else {
    b = d.use(moveaxis(b, -2, -1));
  }
  if (transposeA) {
    a = d.use(moveaxis(a, -2, -1));
    lower = !lower;
  }
  let x = core.triSolve(a, b, { lower, unitDiagonal }) as Array;
  if (leftSide) {
    d.use(x);
    x = moveaxis(x, -2, -1);
  }
  return x;
}

// ── Analytical small-matrix Cholesky ─────────────────────────────────────

/**
 * Maximum matrix dimension for unrolled Cholesky-Banachiewicz.
 * n=4 → ~30 traced ops. Matches inv analytical threshold.
 * @internal
 */
const CHOLESKY_UNROLL_LIMIT = 4;

/**
 * Unrolled Cholesky-Banachiewicz for 2D matrices (no batch dims).
 * Produces lower-triangular L such that A = L @ L^T.
 *
 * All operations are standard elementwise ops (mul, sub, div, sqrt, stack)
 * that trace to fusable Kernel steps — no Routine dispatch.
 * AD works natively through these ops without custom rules.
 *
 * @internal
 */
function cholesky2D(a: Array): Array {
  const n = a.shape[0] as number;

  // L[i][j] for j <= i — scalar traced arrays
  const L: Array[][] = [];

  for (let i = 0; i < n; i++) {
    L[i] = [];
    for (let j = 0; j <= i; j++) {
      // Extract a[i, j]
      const row_i = laxLib.dynamicIndexInDim(a, i, 0);
      const a_ij = laxLib.dynamicIndexInDim(row_i, j, 0);
      row_i.dispose();

      if (i === j) {
        // Diagonal: L[i,i] = sqrt(A[i,i] - sum_{k<i} L[i,k]^2)
        let val = a_ij;
        for (let k = 0; k < i; k++) {
          const sq = numpy.multiply(L[i][k], L[i][k]);
          const next = numpy.subtract(val, sq);
          sq.dispose();
          val.dispose();
          val = next;
        }
        L[i][j] = numpy.sqrt(val);
        val.dispose();
      } else {
        // Off-diagonal: L[i,j] = (A[i,j] - sum_{k<j} L[i,k]*L[j,k]) / L[j,j]
        let val = a_ij;
        for (let k = 0; k < j; k++) {
          const prod = numpy.multiply(L[i][k], L[j][k]);
          const next = numpy.subtract(val, prod);
          prod.dispose();
          val.dispose();
          val = next;
        }
        L[i][j] = numpy.divide(val, L[j][j]);
        val.dispose();
      }
    }
  }

  // Assemble L into [n, n] lower-triangular matrix
  const zero = numpy.array(0, { dtype: a.dtype });
  const rows: Array[] = [];
  for (let i = 0; i < n; i++) {
    const entries: Array[] = new globalThis.Array(n);
    for (let j = 0; j < n; j++) {
      entries[j] = j <= i ? L[i][j] : zero;
    }
    rows.push(numpy.stack(entries, 0));
  }

  const result = numpy.stack(rows, 0);

  // Cleanup
  for (const r of rows) r.dispose();
  for (let i = 0; i < n; i++) {
    for (let j = 0; j <= i; j++) L[i][j].dispose();
  }
  zero.dispose();

  return result;
}

/**
 * Batched unrolled Cholesky.
 * Uses vmap to map over batch dimensions.
 * @internal
 */
function choleskyBatched(a: Array): Array {
  if (a.ndim === 2) return cholesky2D(a);
  return vmap((a2: Array) => choleskyBatched(a2))(a) as Array;
}

// ── Analytical small-matrix triangular solve ─────────────────────────────

/**
 * Pure-primitive upper-triangular back-substitution for 2D matrices.
 *
 * Solves A @ X = B where A is n×n upper-triangular and B is n×nrhs.
 * Returns X (n×nrhs).
 *
 * For small n (≤ TRISOLVE_UNROLL_LIMIT), the loop is fully unrolled into
 * straight-line jaxpr equations — no foriLoop, no Routine dispatch.
 * This enables fusion into scan/block-map bodies on WebGPU.
 *
 * @internal
 */
const TRISOLVE_UNROLL_LIMIT = 8;

function triangularSolveUpper2D(
  a: Array,
  b: Array,
  unitDiagonal: boolean,
): Array {
  const n = a.shape[0] as number;
  const _nrhs = b.shape[1] as number;

  // Back-substitution: solve A @ X = B for upper-triangular A.
  // x[n-1] = b[n-1] / a[n-1,n-1]
  // x[i] = (b[i] - sum_{j>i} a[i,j]*x[j]) / a[i,i]
  //
  // We build X row by row from bottom to top, then stack.

  const rows: Array[] = new globalThis.Array(n);

  for (let i = n - 1; i >= 0; i--) {
    // b_row = b[i, :] → shape [nrhs]
    let b_row = laxLib.dynamicIndexInDim(b, i, 0);

    // Subtract contributions from already-solved rows below
    for (let j = i + 1; j < n; j++) {
      // a_ij = a[i, j] → scalar
      const a_ij = laxLib.dynamicIndexInDim(
        laxLib.dynamicIndexInDim(a, i, 0),
        j,
        0,
      );
      // x_row_j = rows[j] → shape [nrhs]
      const contrib = numpy.multiply(a_ij, rows[j]);
      a_ij.dispose();
      const newBRow = numpy.subtract(b_row, contrib);
      contrib.dispose();
      b_row.dispose();
      b_row = newBRow;
    }

    if (unitDiagonal) {
      rows[i] = b_row;
    } else {
      // Divide by diagonal: a[i, i]
      const a_ii = laxLib.dynamicIndexInDim(
        laxLib.dynamicIndexInDim(a, i, 0),
        i,
        0,
      );
      rows[i] = numpy.divide(b_row, a_ii);
      a_ii.dispose();
      b_row.dispose();
    }
  }

  // Stack rows into [n, nrhs] matrix
  const expanded = rows.map((r) => numpy.expandDims(r, 0));
  for (const r of rows) r.dispose();
  const result =
    expanded.length === 1
      ? expanded[0]
      : (core.concatenate(expanded, 0) as Array);
  for (const e of expanded) if (e !== result) e.dispose();
  return result;
}

/**
 * Pure-primitive triangular solve for 2D matrices.
 *
 * Handles both upper and lower triangular via flip.
 * @internal
 */
function triangularSolve2D(
  a: Array,
  b: Array,
  {
    leftSide,
    lower,
    transposeA,
    unitDiagonal,
  }: {
    leftSide: boolean;
    lower: boolean;
    transposeA: boolean;
    unitDiagonal: boolean;
  },
): Array {
  using d = new DisposableStack();
  if (!leftSide) {
    transposeA = !transposeA;
  } else {
    b = d.use(moveaxis(b, -2, -1));
  }
  if (transposeA) {
    a = d.use(moveaxis(a, -2, -1));
    lower = !lower;
  }
  // Now: solve upper-triangular A @ X = B, where A is [n,n], B is [nrhs,n]
  // Core convention: A upper-triangular, A @ X^T = B^T → X = B @ A^{-T}
  // Our polyfill solves A @ X = B directly (upper-triangular).
  // To match core.triSolve convention: it takes (A_upper, B) where
  // A_upper @ X^T = B^T. So X^T[:,j] = A^{-1} @ B^T[:,j].
  // Equivalently solve A @ Y = B^T then X = Y^T.
  if (lower) {
    // Lower-triangular: flip to upper, solve, flip back
    const aFlipped = d.use(core.flip(a, [-2, -1]) as Array);
    const bFlipped = d.use(core.flip(b, [-1]) as Array);
    // Transpose B to get RHS for A @ X = B^T convention
    const bT = d.use(moveaxis(bFlipped, -2, -1));
    const yT = d.use(triangularSolveUpper2D(aFlipped, bT, unitDiagonal));
    const y = d.use(moveaxis(yT, -2, -1));
    let x = core.flip(y, [-1]) as Array;
    if (leftSide) {
      d.use(x);
      x = moveaxis(x, -2, -1);
    }
    return x;
  } else {
    // Upper-triangular: transpose B, solve, transpose back
    const bT = d.use(moveaxis(b, -2, -1));
    const yT = d.use(triangularSolveUpper2D(a, bT, unitDiagonal));
    let x = moveaxis(yT, -2, -1);
    if (leftSide) {
      d.use(x);
      x = moveaxis(x, -2, -1);
    }
    return x;
  }
}

/**
 * Batched pure-primitive triangular solve.
 * Uses vmap to map over batch dimensions.
 * @internal
 */
function triangularSolveBatched(
  a: Array,
  b: Array,
  opts: {
    leftSide: boolean;
    lower: boolean;
    transposeA: boolean;
    unitDiagonal: boolean;
  },
): Array {
  if (a.ndim === 2) return triangularSolve2D(a, b, opts);
  return vmap((a2: Array, b2: Array) => triangularSolveBatched(a2, b2, opts))(
    a,
    b,
  ) as Array;
}

/**
 * Pure-primitive Householder QR decomposition for 2D matrices.
 *
 * When k = min(m,n) ≤ QR_UNROLL_LIMIT, the Householder iterations are
 * fully unrolled into straight-line jaxpr equations (no foriLoop).
 * This eliminates `hasLoops` / `fori_loop` from scan bodies and allows
 * the block-map fusion machinery to produce a single fused WGSL dispatch.
 *
 * @internal
 */
const QR_UNROLL_LIMIT = 8;

function householderQR2D(a: Array): [Array, Array] {
  const m = a.shape[0] as number;
  const n = a.shape[1] as number;
  const k = Math.min(m, n);
  const dtype = a.dtype;

  const Q = numpy.eye(m, { dtype });
  const R: Array = a;

  // Under PE tracing (grad/jit), these concrete arrays become jaxpr
  // consts referenced by the backward pass. They must NOT be disposed
  // while tracing — the ClosedJaxpr manages their lifetime via
  // creation-ref balancing. In eager mode, we dispose them explicitly.
  const arange_m = numpy.arange(m);
  const arange_n = numpy.arange(n);

  const body = (j: any, carry: any) => {
    const [Q_curr, R_curr] = carry;

    // Extract column j via one-hot mask
    const j_mask_n = numpy.equal(arange_n, j);
    let col = numpy.sum(numpy.where(j_mask_n, R_curr, 0), 1);

    // Zero entries above diagonal (i < j)
    const row_mask = numpy.greaterEqual(arange_m, j);
    col = numpy.where(row_mask, col, 0);

    const colSq = numpy.square(col);
    const normCol = numpy.sqrt(numpy.sum(colSq));

    // Extract r_jj = col[j]
    const j_mask_m = numpy.equal(arange_m, j);
    const r_jj = numpy.sum(numpy.where(j_mask_m, col, 0));

    const zero = numpy.array(0, { dtype });
    const one = numpy.array(1, { dtype });
    const signVal = numpy.where(numpy.equal(r_jj, zero), one, numpy.sign(r_jj));

    const shift = numpy.multiply(signVal, normCol);
    const shiftVec = numpy.multiply(shift, numpy.where(j_mask_m, 1, 0));
    const vUnscaled = numpy.add(col, shiftVec);

    const normV = numpy.sqrt(numpy.sum(numpy.square(vUnscaled)));
    const isZero = numpy.equal(normV, zero);
    const safeNormV = numpy.where(isZero, one, normV);
    let v = numpy.divide(vUnscaled, safeNormV);
    v = numpy.where(isZero, zero, v);

    const v_col = numpy.expandDims(v, 1);
    const v_row = numpy.expandDims(v, 0);
    const vvTR = numpy.multiply(v_col, v_row);

    const H = numpy.subtract(numpy.eye(m, { dtype }), numpy.multiply(2, vvTR));

    const R_next = numpy.dot(H, R_curr);
    const Q_next = numpy.dot(Q_curr, H);

    return [Q_next, R_next];
  };

  let Q_out: Array, R_out: Array;

  if (k <= QR_UNROLL_LIMIT && core.inMakeJaxprBody()) {
    // Unroll: each iteration traces inline as kernel equations.
    // No foriLoop → no hasLoops → eligible for block-map fusion.
    // Only when inside makeJaxpr tracing (JIT/scan body) — in eager mode,
    // JVP, or vmap, foriLoop traces the body internally and manages lifetimes.
    let carry: any[] = [Q, R];
    for (let j = 0; j < k; j++) {
      const [Q_prev, R_prev] = carry;
      carry = body(j, carry);
      Q_prev.dispose();
      // Don't dispose R at j=0 — it's the input `a`, owned by caller
      if (j > 0) R_prev.dispose();
    }
    [Q_out, R_out] = carry as [Array, Array];
  } else {
    const result = laxLib.foriLoop(0, k, body, [Q, R]);
    [Q_out, R_out] = result as [Array, Array];
    Q.dispose();
  }

  // In eager mode, dispose the arange index arrays explicitly.
  // During tracing, the jaxpr owns them via creation-ref balancing — do not dispose.
  if (!core.inMakeJaxprBody()) {
    arange_m.dispose();
    arange_n.dispose();
  }

  let Qthin: Array = Q_out;
  let Rupper: Array = R_out;
  if (k < m) {
    Qthin = laxLib.sliceInDim(Q_out, 0, k, 1);
    Rupper = laxLib.sliceInDim(R_out, 0, k, 0);
  }

  if (Qthin !== Q_out) Q_out.dispose();
  if (Rupper !== R_out) R_out.dispose();

  return [Qthin, Rupper];
}

/**
 * Batched pure-primitive Householder QR.
 * Uses vmap to map over batch dimensions instead of JS-level loops.
 * @internal
 */
function householderQRBatched(a: Array): [Array, Array] {
  if (a.ndim === 2) return householderQR2D(a);
  // vmap over leading batch dimension; recurse for nested batch dims
  return vmap(householderQRBatched)(a) as [Array, Array];
}
