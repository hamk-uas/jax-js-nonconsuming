// Linear algebra functions, mirroring `jax.lax.linalg`.

import { moveaxis } from "./numpy";
import { Array, type ArrayLike, fudgeArray } from "../frontend/array";
import * as core from "../frontend/core";

/**
 * Compute the Cholesky decomposition of a symmetric positive-definite matrix.
 *
 * The Cholesky decomposition of a matrix `A` is:
 *
 * - A = L @ L^T  (for upper=false, default)
 * - A = U^T @ U  (for upper=true)
 *
 * where `L` is a lower-triangular matrix and `U` is an upper-triangular matrix.
 * The input matrix must be symmetric and positive-definite.
 *
 * @example
 * ```ts
 * import { lax, numpy as np } from "@hamk-uas/jax-js-nonconsuming";
 *
 * using x = np.array([[2., 1.], [1., 2.]]);
 *
 * // Lower Cholesky factorization (default):
 * using L = lax.linalg.cholesky(x);
 * // L ≈ [[1.4142135, 0], [0.70710677, 1.2247449]]
 *
 * // Upper Cholesky factorization:
 * using U = lax.linalg.cholesky(x, { upper: true });
 * // U ≈ [[1.4142135, 0.70710677], [0, 1.2247449]]
 * ```
 */
export function cholesky(
  a: ArrayLike,
  { upper = false }: { upper?: boolean } = {},
): Array {
  if (upper) {
    using L = core.cholesky(a) as Array;
    return moveaxis(L, -2, -1);
  }
  return core.cholesky(a) as Array;
}

/**
 * LU decomposition with partial pivoting.
 *
 * Computes the matrix decomposition: `P @ A = L @ U`, where `P` is a
 * permutation of the rows of `A`, `L` is lower-triangular with unit diagonal,
 * and `U` is upper-triangular.
 *
 * @param x - A batch of matrices with shape `[..., m, n]`.
 *
 * @returns A tuple `(lu, pivots, permutation)` where:
 * - `lu`: combined lower and upper triangular matrices.
 * - `pivots`: an array of pivot indices with shape `[..., min(m, n)]`.
 * - `permutation`: the permutation generated by pivots with shape `[..., m]`.
 *
 * @example
 * ```ts
 * import { lax, numpy as np } from "@hamk-uas/jax-js-nonconsuming";
 *
 * const A = np.array([[4., 3.], [6., 3.]]);
 * const [lu, pivots, permutation] = lax.linalg.lu(A);
 * // lu ≈ [[6., 3.], [0.6666667, 1.0]]
 * // pivots = [1, 1]
 * // permutation = [1, 0]
 *
 * A.dispose();
 * lu.dispose();
 * pivots.dispose();
 * permutation.dispose();
 * ```
 */
export function lu(x: ArrayLike): [Array, Array, Array] {
  return core.lu(x) as [Array, Array, Array];
}

/**
 * QR decomposition.
 *
 * Computes the thin QR factorization `A = Q @ R`, where `Q` has orthonormal
 * columns and `R` is upper triangular.
 *
 * @param a - A batch of matrices with shape `[..., m, n]` where `m >= n`.
 *
 * @returns A tuple `[Q, R]` where:
 * - `Q`: orthogonal matrix with shape `[..., m, k]`, `k = min(m, n)`.
 * - `R`: upper triangular matrix with shape `[..., k, n]`.
 *
 * @example
 * ```ts
 * import { lax, numpy as np } from "@hamk-uas/jax-js-nonconsuming";
 *
 * const A = np.array([[1., 2.], [3., 4.], [5., 6.]]);
 * const [Q, R] = lax.linalg.qr(A);
 * // Q has shape [3, 2], R has shape [2, 2]
 * // Q^T @ Q ≈ I, Q @ R ≈ A
 *
 * A.dispose();
 * Q.dispose();
 * R.dispose();
 * ```
 */
export function qr(a: ArrayLike): [Array, Array] {
  return core.qr(a) as [Array, Array];
}

/**
 * Solve a triangular linear system.
 *
 * Solves `a @ x = b` (if leftSide=true) or `x @ a = b` (if leftSide=false)
 * where `a` is a triangular matrix.
 *
 * @example
 * ```ts
 * import { lax, numpy as np } from "@hamk-uas/jax-js-nonconsuming";
 *
 * using L = np.array([[2., 0.], [1., 3.]]);
 * using b = np.array([4., 7.]).reshape([2, 1]);
 *
 * // Solve L @ x = b
 * using x = lax.linalg.triangularSolve(L, b, { leftSide: true, lower: true });
 * // x = [[2.], [5./3.]]
 * ```
 */
export function triangularSolve(
  a: ArrayLike,
  b: ArrayLike,
  {
    leftSide = false,
    lower = false,
    transposeA = false,
    unitDiagonal = false,
  }: {
    leftSide?: boolean;
    lower?: boolean;
    transposeA?: boolean;
    unitDiagonal?: boolean;
  } = {},
): Array {
  a = fudgeArray(a);
  b = fudgeArray(b);
  const d: Array[] = [];
  try {
    if (!leftSide) {
      // Transpose everything so it becomes a left-side solve.
      // Note that the `TriangularSolve` primitive automatically transposes the
      // b and x (output) values.
      transposeA = !transposeA;
    } else {
      b = moveaxis(b, -2, -1);
      d.push(b);
    }
    if (transposeA) {
      a = moveaxis(a, -2, -1);
      d.push(a);
      lower = !lower;
    }
    let x = core.triangularSolve(a, b, { lower, unitDiagonal }) as Array;
    if (leftSide) {
      d.push(x);
      x = moveaxis(x, -2, -1);
    }
    return x;
  } finally {
    for (const v of d) v[Symbol.dispose]();
  }
}
